# 1. B的详细设计-GUI与控制模块
doc = Document()
title = doc.add_heading('详细设计-GUI与控制模块（易雨杰 2024611209）', 0)
title.alignment = WD_ALIGN_PARAGRAPH.CENTER

doc.add_heading('3.2 GUI与控制模块', level=1)
doc.add_paragraph('GUI与控制模块负责提供用户操作界面、接收用户输入、调度后台计算任务，并将算法、可视化和文件IO的结果整合展示在统一窗口中。界面基于Java Swing实现，采用三栏布局，核心控制逻辑由MainController统一管理，所有耗时计算在后台线程执行，保证界面响应流畅。')

doc.add_heading('3.2.1 主窗口与布局设计', level=2)
doc.add_paragraph('MainFrame是程序的主窗口，整体采用顶部工具栏、中部三栏分割面板、底部状态栏的结构。中部使用JSplitPane水平分割为三个区域：左侧输入面板、中间图画布、右侧结果面板，各栏宽度可由用户拖拽调整，窗口大小改变时自动适配。')
doc.add_paragraph('顶部工具栏放置高频操作按钮，包括打开文件、清空输入、开始计算、取消计算、导出结果、导出图片和布局切换按钮。按钮通过统一的样式工具配置，保持大小、颜色和间距一致。底部状态栏分为左右两部分，左侧显示节点数、边数和结果总数，右侧显示当前操作的状态提示。')
doc.add_paragraph('左侧InputPanel是多行文本编辑区，用户可以直接粘贴或手动输入关系数据，下方放置导入文件、清空和示例数据按钮。右侧ResultPanel采用分页列表显示拓扑排序结果，每页固定显示20条，底部提供翻页和复制按钮，避免一次性渲染过多条目造成界面卡顿。整体布局在1280×720分辨率下各区域都能完整显示，窗口最小化时输入区和结果列表自动收缩滚动。')

doc.add_heading('3.2.2 主控制器任务调度设计', level=2)
doc.add_paragraph('MainController是GUI层和底层模块之间的中间层，负责接收UI事件、调度后台线程、对接A的算法模块、C的可视化模块和D的IO模块。所有耗时计算都通过SwingWorker在后台线程执行，避免阻塞事件dispatch线程造成界面假死。')
doc.add_paragraph('用户点击计算按钮后，控制器首先校验输入非空，随后创建后台任务：先调用D的解析模块将文本转换为图结构，再调用A的全枚举算法计算所有拓扑序列。计算过程中控制器持续响应取消事件，用户点击取消时设置中断标记，算法在每层递归前检查标记，及时停止搜索。计算完成后，控制器回到UI线程，将图传给画布组件，将排序结果传给结果列表，同时更新状态栏的统计信息。')
doc.add_paragraph('控制器还负责处理跨模块联动：用户在结果列表中选中某一行时，控制器将该序列和选中序号传给画布，高亮对应路径；用户点击导出按钮时，控制器将结果列表和完整性信息传给文件导出模块，确保导出文件头记录结果是否完整和停止原因。所有异常都通过统一弹窗捕获展示，错误信息包含具体行号和原因，方便用户定位问题。')

doc.add_heading('3.2.3 结果面板与交互设计', level=2)
doc.add_paragraph('ResultPanel使用JList渲染排序结果，采用分页机制，内部维护完整结果列表和当前页码。每页20条数据，用户点击翻页按钮时切换当前显示的子列表。列表项默认使用->分隔节点，例如MA 140 -> MA 150 -> CS 101，和界面显示、导出文件格式保持一致。')
doc.add_paragraph('用户单击某一行结果时，面板通过监听器将该序列回调给控制器，控制器通知画布高亮这条拓扑序对应的节点和边。为了区分不同结果，画布根据结果序号轮换五种高亮颜色，节点右上角同时标注顺序序号，用户切换不同结果时能清晰看到路径变化。用户双击某一行时，面板将该条序列拼接成字符串复制到剪贴板，方便直接使用。')
doc.add_paragraph('面板顶部显示当前结果总数和是否完整的提示，底部显示当前页和总页数，配合上一页、下一页和复制按钮使用。分页机制既保证了上千条结果时界面仍然流畅，又避免了用户一次性浏览过多内容造成信息过载。')

doc.add_heading('3.2.4 界面样式统一设计', level=2)
doc.add_paragraph('UIStyle工具类统一管理所有界面组件的配色、字体和按钮样式。工具栏按钮和画布上的悬浮按钮都通过统一方法配置，保证圆角、边框、悬停效果和文字大小一致。界面主色采用低饱和度蓝色，正常状态为浅蓝背景，悬停时加深，和整体浅色主题协调。')
doc.add_paragraph('开发过程中发现部分特殊Unicode符号在Windows Swing下显示为方框，最终按钮上统一使用中文文字标注，避免乱码问题。字体统一使用系统默认无衬线字体，正文和按钮文字大小保持一致，状态栏和提示文字稍小一级，形成清晰的视觉层次。所有弹窗使用统一的标题和图标，错误提示使用红色边框，普通提示使用蓝色边框，保持交互风格一致。')

doc.save(r'E:\tp\docs\报告\详细设计-GUI与控制模块-易雨杰.docx')
